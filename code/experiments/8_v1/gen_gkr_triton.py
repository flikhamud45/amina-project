"""Generates code/src/pvi/fullcheck/gkr_triton.py (the unrolled F_{p^8} product is written out)."""
import pathlib

OUT = pathlib.Path(__file__).resolve().parents[2] / "src" / "pvi" / "fullcheck" / "gkr_triton.py"
D = 8


def args(prefix):
    return ", ".join(f"{prefix}{i}" for i in range(D))


def emul():
    lines = [f"@triton.jit", f"def _emul({args('a')}, {args('b')}, P, MU, B11):",
             '    """``a b`` in ``F_{p^8}`` (Montgomery planes): ``c_k = sum_{i+j=k} a_i b_j + 11 sum_{i+j=k+8} a_i b_j``."""']
    for k in range(D):
        low = [(i, k - i) for i in range(D) if 0 <= k - i < D]
        high = [(i, k + D - i) for i in range(D) if 0 <= k + D - i < D]
        expr = None
        for i, j in low:
            term = f"_mm(a{i}, b{j}, P, MU)"
            expr = term if expr is None else f"_add({expr}, {term}, P)"
        lines.append(f"    c{k} = {expr}")
        if high:
            h = None
            for i, j in high:
                term = f"_mm(a{i}, b{j}, P, MU)"
                h = term if h is None else f"_add({h}, {term}, P)"
            lines.append(f"    c{k} = _add(c{k}, _mm({h}, B11, P, MU), P)")
    lines.append(f"    return {args('c')}")
    return "\n".join(lines)


def load(name, ptr, idx, stride, mask):
    return "\n".join(f"    {name}{k} = tl.load({ptr} + {k} * {stride} + {idx}, mask={mask}, other=0).to(tl.uint32, bitcast=True)"
                     for k in range(D))


def store(name, ptr, idx, stride, mask):
    return "\n".join(f"    tl.store({ptr} + {k} * {stride} + {idx}, {name}{k}.to(tl.int32, bitcast=True), mask={mask})"
                     for k in range(D))


def ext2(fn, out, a, b):
    return "\n".join(f"    {out}{k} = {fn}({a}{k}, {b}{k}, P)" for k in range(D))


def emul_call(out, a, b):
    return f"    {args(out)} = _emul({args(a)}, {args(b)}, P, MU, B11)"


HEADER = '''"""The fractional-sum GKR prover of V1 on the GPU (Triton): ``V1_SPEC.md`` Sec. 5.4.

Generated by ``gen_gkr_triton.py`` (the product in ``F_{p^8}`` is unrolled); same transcript as
:func:`logup_gkr.prove`, byte for byte (``tests/test_gkr_triton.py``, on a CUDA host).

**Arithmetic.** BabyBear in Montgomery form on uint32 (``R = 2^32``): ``mm(a, b) = a b R^-1 mod p`` by
``lo = a b``, ``hi = umulhi(a, b)``, ``q = lo p^-1 mod 2^32``, ``t = hi - umulhi(q, p)`` (``+ p`` if negative); sums by
an add and a conditional subtraction.  An element of ``F = F_p[x]/(x^8 - 11)`` is 8 planes; arrays are
structure-of-arrays ``[8, n]`` int32 tensors (the bits of the uint32 values).  The verifier-facing values (the top,
the round polynomials, the child values) are converted to canonical form on the host.

**Algorithm** (as the eager prover): the leaves of an instance are built on the device from the residues and
widths (``leaves``) or uploaded (``prove``); the tree is combined layer by layer; for each layer ``k`` the child
arrays are split into their even and odd halves, the eq table of the layer's point is built by doubling, and each
sum-check round is one kernel (``_round_kernel``: the three values ``g(0), g(2), g(3)`` summed per block in 64 bits)
then one fold of the five arrays at the round's challenge (``_fold_kernel``), with one host round trip per round.
"""

from __future__ import annotations

import os
import sysconfig

import torch

from . import extfield as ef
from .field import P as PRIME

_INCLUDE = os.environ.get("PVI_PY_INCLUDE")
if _INCLUDE:
    _paths = sysconfig.get_paths
    sysconfig.get_paths = lambda *a, **k: {**_paths(*a, **k), "include": _INCLUDE}

try:
    import triton
    import triton.language as tl
except ImportError:                    # pragma: no cover - CPU-only environments
    triton = None

__all__ = ["available", "prove", "prove_leaves"]

R_MOD = (1 << 32) % PRIME
R2 = (1 << 64) % PRIME
R_INV = pow(1 << 32, -1, PRIME)
MU = pow(PRIME, -1, 1 << 32)
B11 = 11 * R_MOD % PRIME
BLOCK = 256


def available(device) -> bool:
    return triton is not None and torch.device(device).type == "cuda"


def _to_mont(v: torch.Tensor) -> list[int]:
    """Canonical ``[8]`` -> 8 Montgomery ints."""
    return [int(c) * R_MOD % PRIME for c in v.tolist()]


def _from_mont(planes: torch.Tensor) -> torch.Tensor:
    """Montgomery values (int64 tensor, any shape, in ``[0, p)``) -> canonical int64."""
    return (planes.to(torch.int64) % PRIME) * R_INV % PRIME


def _consts():
    return dict(P_=PRIME, MU_=MU, B11_=B11)


if triton is not None:
    @triton.jit
    def _mm(a, b, P, MU):
        lo = a * b
        hi = tl.umulhi(a, b)
        q = lo * MU
        u = tl.umulhi(q, P)
        t = hi - u
        return tl.where(hi < u, t + P, t)

    @triton.jit
    def _add(a, b, P):
        s = a + b
        return tl.where(s >= P, s - P, s)

    @triton.jit
    def _sub(a, b, P):
        d = a - b
        return tl.where(a < b, d + P, d)

'''


def indent(s, n=4):
    return "\n".join((" " * n + line) if line else line for line in s.split("\n"))


def kernels():
    parts = []
    # ---- leaves
    parts.append(f'''@triton.jit
def _leaf_kernel(d_ptr, w_ptr, p_ptr, q_ptr, {args('al')}, rows, T, n_col, total, stride, P_, MU_, R2_, ONE_,
                 BLOCK: tl.constexpr):
    P = P_.to(tl.uint32)
    MU = MU_.to(tl.uint32)
    R2 = R2_.to(tl.uint32)
    ONE = ONE_.to(tl.uint32)
    i = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
    inb = i < total
    row = i >> n_col
    col = i & ((1 << n_col) - 1)
    real = (row < rows) & (col < T) & inb
    src = row * T + col
    d = tl.load(d_ptr + src, mask=real, other=0).to(tl.uint32, bitcast=True)
    w = tl.load(w_ptr + src, mask=real, other=0).to(tl.uint32, bitcast=True)
    dm = _mm(d, R2, P, MU)
    wm = _mm(w, R2, P, MU)
    zero = d * 0
''' + "\n".join(
        [f"    q0 = tl.where(real, _sub(al0.to(tl.uint32), dm, P), ONE + zero)",
         f"    q1 = tl.where(real, _sub(al1.to(tl.uint32), wm, P), zero)"]
        + [f"    q{k} = tl.where(real, al{k}.to(tl.uint32) + zero, zero)" for k in range(2, D)]
        + [f"    p0 = tl.where(real, ONE + zero, zero)"]) + "\n"
        + "\n".join(f"    tl.store(p_ptr + {k} * stride + i, (p0 if {k} == 0 else zero).to(tl.int32, bitcast=True), mask=inb)"
                    .replace(f"(p0 if {k} == 0 else zero)", "p0" if k == 0 else "zero") for k in range(D)) + "\n"
        + store("q", "q_ptr", "i", "stride", "inb"))
    # ---- combine
    parts.append(f'''@triton.jit
def _combine_kernel(pi, qi, po, qo, m_out, s_in, s_out, P_, MU_, B11_, BLOCK: tl.constexpr):
    P = P_.to(tl.uint32)
    MU = MU_.to(tl.uint32)
    B11 = B11_.to(tl.uint32)
    y = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
    mask = y < m_out
''' + load("pl", "pi", "2 * y", "s_in", "mask") + "\n" + load("pr", "pi", "2 * y + 1", "s_in", "mask") + "\n"
        + load("ql", "qi", "2 * y", "s_in", "mask") + "\n" + load("qr", "qi", "2 * y + 1", "s_in", "mask") + "\n"
        + emul_call("u", "pl", "qr") + "\n" + emul_call("v", "pr", "ql") + "\n" + ext2("_add", "np", "u", "v") + "\n"
        + emul_call("nq", "ql", "qr") + "\n" + store("np", "po", "y", "s_out", "mask") + "\n"
        + store("nq", "qo", "y", "s_out", "mask"))
    # ---- eq doubling
    parts.append(f'''@triton.jit
def _eq_kernel(ti, to, {args('r')}, {args('s')}, m, s_in, s_out, P_, MU_, B11_, BLOCK: tl.constexpr):
    P = P_.to(tl.uint32)
    MU = MU_.to(tl.uint32)
    B11 = B11_.to(tl.uint32)
    y = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
    mask = y < m
''' + load("t", "ti", "y", "s_in", "mask") + "\n"
        + "\n".join(f"    rr{k} = r{k}.to(tl.uint32) + t0 * 0" for k in range(D)) + "\n"
        + "\n".join(f"    ss{k} = s{k}.to(tl.uint32) + t0 * 0" for k in range(D)) + "\n"
        + emul_call("lo", "t", "ss") + "\n" + emul_call("hi", "t", "rr") + "\n"
        + store("lo", "to", "y", "s_out", "mask") + "\n" + store("hi", "to", "y + m", "s_out", "mask"))
    # ---- one round
    body = [f'''@triton.jit
def _round_kernel(e, pl, pr, ql, qr, out, {args('lam')}, half, s, P_, MU_, B11_, BLOCK: tl.constexpr):
    P = P_.to(tl.uint32)
    MU = MU_.to(tl.uint32)
    B11 = B11_.to(tl.uint32)
    pid = tl.program_id(0)
    y = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
    mask = y < half''']
    for nm, ptr in (("e", "e"), ("pl", "pl"), ("pr", "pr"), ("ql", "ql"), ("qr", "qr")):
        body.append(load(f"{nm}0_", ptr, "2 * y", "s", "mask").replace(f"{nm}0_", f"{nm}a"))
        body.append(load(f"{nm}1_", ptr, "2 * y + 1", "s", "mask").replace(f"{nm}1_", f"{nm}b"))
        body.append("\n".join(f"    {nm}d{k} = _sub({nm}b{k}, {nm}a{k}, P)" for k in range(D)))
    body.append("\n".join(f"    lm{k} = lam{k}.to(tl.uint32) + ea0 * 0" for k in range(D)))
    for ti, t in enumerate((0, 2, 3)):
        for nm in ("e", "pl", "pr", "ql", "qr"):
            if t == 0:
                body.append("\n".join(f"    {nm}t{k} = {nm}a{k}" for k in range(D)))
            elif t == 2:
                body.append("\n".join(f"    {nm}t{k} = _add({nm}b{k}, {nm}d{k}, P)" for k in range(D)))
            else:
                body.append("\n".join(f"    {nm}t{k} = _add({nm}t{k}, {nm}d{k}, P)" for k in range(D)))
        body.append(emul_call("f1_", "plt", "qrt"))
        body.append(emul_call("f2_", "prt", "qlt"))
        body.append(emul_call("f3_", "qlt", "qrt"))
        body.append(emul_call("f4_", "lm", "f3_"))
        body.append("\n".join(f"    ff{k} = _add(_add(f1_{k}, f2_{k}, P), f4_{k}, P)" for k in range(D)))
        body.append(emul_call("g_", "et", "ff"))
        body.append("\n".join(
            f"    tl.store(out + (pid * 3 + {ti}) * 8 + {k}, tl.sum(tl.where(mask, g_{k}, 0).to(tl.uint64), axis=0).to(tl.int64))"
            for k in range(D)))
    parts.append("\n".join(body))
    # ---- fold of the five arrays
    body = [f'''@triton.jit
def _fold_kernel(e, pl, pr, ql, qr, eo, plo, pro, qlo, qro, {args('r')}, half, s_in, s_out, P_, MU_, B11_,
                 BLOCK: tl.constexpr):
    P = P_.to(tl.uint32)
    MU = MU_.to(tl.uint32)
    B11 = B11_.to(tl.uint32)
    y = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
    mask = y < half''']
    first = True
    for nm, ptr, optr in (("e", "e", "eo"), ("pl", "pl", "plo"), ("pr", "pr", "pro"), ("ql", "ql", "qlo"),
                          ("qr", "qr", "qro")):
        body.append(load(f"{nm}a", ptr, "2 * y", "s_in", "mask"))
        body.append(load(f"{nm}b", ptr, "2 * y + 1", "s_in", "mask"))
        if first:
            body.append("\n".join(f"    rr{k} = r{k}.to(tl.uint32) + ea0 * 0" for k in range(D)))
            first = False
        body.append("\n".join(f"    {nm}d{k} = _sub({nm}b{k}, {nm}a{k}, P)" for k in range(D)))
        body.append(emul_call(f"{nm}m", f"{nm}d", "rr"))
        body.append("\n".join(f"    {nm}o{k} = _add({nm}a{k}, {nm}m{k}, P)" for k in range(D)))
        body.append(store(f"{nm}o", optr, "y", "s_out", "mask"))
    parts.append("\n".join(body))
    return parts


HOST = '''

def _grid(n: int):
    return (max(1, triton.cdiv(n, BLOCK)),)


def _planes_mont(a: torch.Tensor, device) -> torch.Tensor:
    """Canonical AoS ``[n, 8]`` int64 -> Montgomery SoA ``[8, n]`` int32 on ``device`` (tests and small inputs)."""
    m = (a.to(torch.int64) % PRIME) * R_MOD % PRIME
    return m.T.contiguous().to(torch.int32).to(device)


def _combine(p: torch.Tensor, q: torch.Tensor):
    m = p.shape[1] // 2
    po = torch.empty(8, m, dtype=torch.int32, device=p.device)
    qo = torch.empty_like(po)
    _combine_kernel[_grid(m)](p, q, po, qo, m, p.shape[1], m, **_consts(), BLOCK=BLOCK)
    return po, qo


def _eq_table(rho_mont: list[list[int]], device) -> torch.Tensor:
    t = torch.zeros(8, 1, dtype=torch.int32, device=device)
    t[0, 0] = R_MOD
    for r in rho_mont:
        m = t.shape[1]
        s = [(R_MOD - r[0]) % PRIME] + [(PRIME - c) % PRIME for c in r[1:]]
        out = torch.empty(8, 2 * m, dtype=torch.int32, device=device)
        _eq_kernel[_grid(m)](t, out, *r, *s, m, m, 2 * m, **_consts(), BLOCK=BLOCK)
        t = out
    return t


def _absorb(ch, label: str, v: torch.Tensor) -> None:
    ch.absorb(label.encode(), v.reshape(-1).to(torch.int64).contiguous().cpu().numpy().tobytes())


def _prove_tree(layers: list, ch, label: str):
    """The transcript from the tree's layers (``layers[k]``: Montgomery SoA ``(p, q)`` of ``2^k`` nodes)."""
    from .logup_gkr import Transcript

    n = len(layers) - 1
    p1, q1 = layers[1]
    top = _from_mont(torch.stack([p1[:, 0], p1[:, 1], q1[:, 0], q1[:, 1]]).cpu())
    tr = Transcript(n, top)
    _absorb(ch, label + "top", top)
    rho = [ch.ext(label + "mu0")[0]]
    dev = p1.device
    for k in range(1, n):
        lam = ch.ext(label + f"lam{k}")[0]
        cp, cq = layers[k + 1]
        arrs = [_eq_table([_to_mont(r) for r in rho], dev),
                cp[:, 0::2].contiguous(), cp[:, 1::2].contiguous(), cq[:, 0::2].contiguous(), cq[:, 1::2].contiguous()]
        layers[k + 1] = None                     # its halves are all this layer reads
        lam_m = _to_mont(lam)
        rounds, rs = [], []
        for j in range(k):
            m = arrs[0].shape[1]
            half = m // 2
            nb = _grid(half)[0]
            part = torch.empty(nb, 3, 8, dtype=torch.int64, device=dev)
            _round_kernel[(nb,)](*arrs, part, *lam_m, half, m, **_consts(), BLOCK=BLOCK)
            g = _from_mont(part.sum(0).cpu() % PRIME)
            _absorb(ch, label + f"g{k}.{j}", g)
            rounds.append(g)
            r = ch.ext(label + f"r{k}.{j}")[0]
            rs.append(r)
            outs = [torch.empty(8, half, dtype=torch.int32, device=dev) for _ in range(5)]
            _fold_kernel[_grid(half)](*arrs, *outs, *_to_mont(r), half, m, half, **_consts(), BLOCK=BLOCK)
            arrs = outs
        vals = _from_mont(torch.stack([a[:, 0] for a in arrs[1:]]).cpu())
        _absorb(ch, label + f"v{k}", vals)
        tr.rounds.append(torch.stack(rounds))
        tr.vals.append(vals)
        rho = [ch.ext(label + f"mu{k}")[0]] + rs
    tr.point = torch.stack(rho)
    return tr


def _tree(p: torch.Tensor, q: torch.Tensor) -> list:
    layers = [(p, q)]
    while layers[-1][0].shape[1] > 1:
        layers.append(_combine(*layers[-1]))
    return layers[::-1]


def prove(p: torch.Tensor, q: torch.Tensor, ch, label: str, device="cuda"):
    """:func:`logup_gkr.prove` on the GPU for canonical leaves ``p, q`` ``[2^n, 8]`` (int64, any device)."""
    return _prove_tree(_tree(_planes_mont(p, device), _planes_mont(q, device)), ch, label)


def prove_leaves(delta: torch.Tensor, width: torch.Tensor, n_col: int, n: int, alpha: torch.Tensor, ch, label: str,
                 device="cuda"):
    """The transcript of the instance whose real entries are ``delta``, ``width`` ``[R, T]`` (integers, as
    :func:`logup.leaves` lays them out), its leaves built on the device."""
    rows, cols = delta.shape
    total = 1 << n
    d = (delta.to(torch.int64) % PRIME).to(torch.int32).to(device).contiguous()
    w = (width.to(torch.int64) % PRIME).to(torch.int32).to(device).contiguous()
    p = torch.empty(8, total, dtype=torch.int32, device=device)
    q = torch.empty_like(p)
    _leaf_kernel[_grid(total)](d, w, p, q, *_to_mont(alpha), rows, cols, n_col, total, total, PRIME, MU, R2, R_MOD,
                               BLOCK=BLOCK)
    del d, w
    return _prove_tree(_tree(p, q), ch, label)
'''


def main():
    text = HEADER + "\n" + indent(emul()) + "\n\n" + "\n\n".join(indent(k) for k in kernels()) + "\n" + HOST
    OUT.write_text(text)
    print(OUT, len(text.splitlines()), "lines")


main()
