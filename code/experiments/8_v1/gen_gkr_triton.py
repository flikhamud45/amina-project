def _grid(n: int):
    return (max(1, triton.cdiv(n, BLOCK)),)


def _planes_mont(a: torch.Tensor, device) -> torch.Tensor:
    """Canonical AoS ``[n, 8]`` int64 -> Montgomery SoA ``[8, n]`` int32 on ``device`` (tests and small inputs)."""
    m = (a.to(torch.int64) % PRIME) * R_MOD % PRIME
    return m.T.contiguous().to(torch.int32).to(device)


def _combine(p: torch.Tensor, q: torch.Tensor):
    m = p.shape[1] // 2
    po = torch.empty(8, m, dtype=torch.int32, device=p.device)
    qo = torch.empty_like(po)
    _combine_kernel[_grid(m)](p, q, po, qo, m, p.shape[1], m, **_consts(), BLOCK=BLOCK)
    return po, qo


def _eq_step(t: torch.Tensor, r: list[int], inter: int) -> torch.Tensor:
    """``t`` ``[8, m]`` times ``(1 - r, r)`` for a new variable: appended as the high bit (``inter = 0``: entries
    ``y`` and ``y + m``) or prepended as the low bit (``inter = 1``: entries ``2y`` and ``2y + 1``)."""
    m = t.shape[1]
    s = [(R_MOD - r[0]) % PRIME] + [(PRIME - c) % PRIME for c in r[1:]]
    out = torch.empty(8, 2 * m, dtype=torch.int32, device=t.device)
    _eq_kernel[_grid(m)](t, out, *r, *s, m, m, 2 * m, inter, **_consts(), BLOCK=BLOCK)
    return out


def _one(device) -> torch.Tensor:
    t = torch.zeros(8, 1, dtype=torch.int32, device=device)
    t[0, 0] = R_MOD
    return t


def _eq_table(rho_mont: list[list[int]], device) -> torch.Tensor:
    """``eq(rho, bits(y))`` ``[8, 2^k]``, bit ``i`` of ``y`` against ``rho[i]`` (as ``extfield.eq_table``)."""
    t = _one(device)
    for r in rho_mont:
        t = _eq_step(t, r, 0)
    return t


def _suffix_tables(rho_mont: list[list[int]], device) -> list[torch.Tensor]:
    """``[eq_table(rho[j+1:]) for j < k]``, built from the last one by prepending one low bit at a time."""
    k = len(rho_mont)
    out = [None] * k
    t = _one(device)
    out[k - 1] = t
    for j in range(k - 2, -1, -1):
        t = _eq_step(t, rho_mont[j + 1], 1)
        out[j] = t
    return out


# -- single elements of F on the host, as lists of 8 Python ints (much cheaper than 8-entry tensors per round)
_ZETA = pow(11, (PRIME - 1) // 8, PRIME)
_ZP = [[pow(_ZETA, i * k, PRIME) for k in range(8)] for i in range(8)]
_INV2, _INV6 = pow(2, PRIME - 2, PRIME), pow(6, PRIME - 2, PRIME)


def _fm(a, b):
    c = [0] * 15
    for i, ai in enumerate(a):
        if ai:
            for j, bj in enumerate(b):
                c[i + j] += ai * bj
    return [(c[k] + 11 * c[k + 8]) % PRIME for k in range(7)] + [c[7] % PRIME]


def _fa(a, b):
    return [(x + y) % PRIME for x, y in zip(a, b)]


def _fs(a, b):
    return [(x - y) % PRIME for x, y in zip(a, b)]


def _fk(a, k: int):
    return [x * k % PRIME for x in a]


def _fc(c: int):
    return [c % PRIME] + [0] * 7


def _finv(a):
    """``a^-1`` through the norm (``extfield.inv``)."""
    b = [x * z % PRIME for x, z in zip(a, _ZP[1])]
    for i in range(2, 8):
        b = _fm(b, [x * z % PRIME for x, z in zip(a, _ZP[i])])
    n = _fm(a, b)[0]
    return _fk(b, pow(n, PRIME - 2, PRIME))


def _flagrange(g0, g1, g2, g3, r):
    """The cubic through ``(t, g_t)``, ``t = 0..3``, at ``r`` (``extfield.lagrange4``)."""
    r1, r2, r3 = _fs(r, _fc(1)), _fs(r, _fc(2)), _fs(r, _fc(3))
    t12, t23 = _fm(r1, r2), _fm(r2, r3)
    l0 = _fk(_fm(t12, r3), PRIME - _INV6)
    l1 = _fk(_fm(r, t23), _INV2)
    l2 = _fk(_fm(_fm(r, r1), r3), PRIME - _INV2)
    l3 = _fk(_fm(r, t12), _INV6)
    out = _fm(l0, g0)
    for li, gi in ((l1, g1), (l2, g2), (l3, g3)):
        out = _fa(out, _fm(li, gi))
    return out


def _li(t: torch.Tensor):
    return [int(v) for v in t.tolist()]


def _absorb(ch, label: str, v: torch.Tensor) -> None:
    ch.absorb(label.encode(), v.reshape(-1).to(torch.int64).contiguous().cpu().numpy().tobytes())


def _prove_tree(layers: list, ch, label: str):
    """The transcript from the tree's layers (``layers[k]``: Montgomery SoA ``(p, q)`` of ``2^k`` nodes)."""
    from .logup_gkr import Transcript

    n = len(layers) - 1
    p1, q1 = layers[1]
    _tick("start", p1.device)
    top = _from_mont(torch.stack([p1[:, 0], p1[:, 1], q1[:, 0], q1[:, 1]]).cpu())
    tr = Transcript(n, top)
    _absorb(ch, label + "top", top)
    rho = [ch.ext(label + "mu0")[0]]
    dev = p1.device
    one = _fc(1)
    prev = [_li(v) for v in top]                 # the values the layer's claim comes from
    for k in range(1, n):
        lam = ch.ext(label + f"lam{k}")[0]
        cp, cq = layers[k + 1]
        arrs = [cp[:, 0::2].contiguous(), cp[:, 1::2].contiguous(), cq[:, 0::2].contiguous(), cq[:, 1::2].contiguous()]
        layers[k + 1] = None                     # its halves are all this layer reads
        _tick("halves", dev)
        lam_m, lam_l = _to_mont(lam), _li(lam)
        mu = _li(rho[0])
        claim = _fa(_fa(prev[0], _fm(mu, _fs(prev[1], prev[0]))),
                    _fm(lam_l, _fa(prev[2], _fm(mu, _fs(prev[3], prev[2])))))
        scale = one                              # prod_{i<j} eq(rho_i, r_i)
        suffixes = _suffix_tables([_to_mont(r) for r in rho], dev)
        _tick("suffix", dev)
        rounds, rs = [], []
        for j in range(k):
            # g_j(t) = scale eq(rho_j, t) h(t), h(t) = sum_y eq(rho_{>j}, y) F(t, y) of degree 2: the kernel gives
            # h(0), h(2); h(1) follows from g(0) + g(1) = claim; the transcript is the eager prover's g(0), g(2), g(3)
            m = arrs[0].shape[1]
            half = m // 2
            nb = _grid(half)[0]
            suffix, suffixes[j] = suffixes[j], None
            part = torch.empty(nb, 2, 8, dtype=torch.int64, device=dev)
            _round2_kernel[(nb,)](suffix, *arrs, part, *lam_m, half, m, **_consts(), BLOCK=BLOCK)
            del suffix
            _tick("round", dev)
            h0, h2 = (_li(v) for v in _from_mont(part.sum(0).cpu() % PRIME))
            rj = _li(rho[j])
            e0, e1 = _fs(one, rj), rj
            e2, e3 = _fs(_fk(rj, 3), one), _fs(_fk(rj, 5), _fc(2))
            g0 = _fm(scale, _fm(e0, h0))
            denom = _fm(scale, e1)
            if not any(denom):                   # probability ~ k / p^8: evaluate h(1) directly instead
                h1 = _li(_h_at_one(arrs, [_to_mont(r) for r in rho], j, lam_m, dev))
            else:
                h1 = _fm(_fs(claim, g0), _finv(denom))
            h3 = _fa(_fs(h0, _fk(h1, 3)), _fk(h2, 3))
            g2, g3 = _fm(scale, _fm(e2, h2)), _fm(scale, _fm(e3, h3))
            g = torch.tensor([g0, g2, g3], dtype=torch.int64)
            _absorb(ch, label + f"g{k}.{j}", g)
            rounds.append(g)
            r = ch.ext(label + f"r{k}.{j}")[0]
            rs.append(r)
            rl = _li(r)
            claim = _flagrange(g0, _fs(claim, g0), g2, g3, rl)
            scale = _fm(scale, _fa(_fm(rj, rl), _fm(_fs(one, rj), _fs(one, rl))))
            _tick("host", dev)
            outs = [torch.empty(8, half, dtype=torch.int32, device=dev) for _ in range(4)]
            _fold4_kernel[_grid(half)](*arrs, *outs, *_to_mont(r), half, m, half, **_consts(), BLOCK=BLOCK)
            arrs = outs
            _tick("fold", dev)
        vals = _from_mont(torch.stack([a[:, 0] for a in arrs]).cpu())
        prev = [_li(v) for v in vals]
        _absorb(ch, label + f"v{k}", vals)
        tr.rounds.append(torch.stack(rounds))
        tr.vals.append(vals)
        rho = [ch.ext(label + f"mu{k}")[0]] + rs
    tr.point = torch.stack(rho)
    return tr


def _h_at_one(arrs, rho, j, lam_m, dev):
    """``h(1)`` of round ``j`` directly (the kernel at ``t = 1``: the odd halves): only when the claim cannot give
    it, i.e. ``prod_{i<j} eq(rho_i, r_i) rho_j = 0``."""
    m = arrs[0].shape[1]
    odd = [a[:, 1::2].contiguous() for a in arrs]
    half = m // 2
    nb = _grid(half)[0]
    suffix = _eq_table(rho[j + 1:], dev)
    part = torch.empty(nb, 2, 8, dtype=torch.int64, device=dev)
    # with A' = (a[2y+1], a[2y+1]) the kernel's t = 0 point is t = 1 of the original arrays
    dup = [torch.stack([o, o], 2).reshape(8, m) for o in odd]
    _round2_kernel[(nb,)](suffix, *dup, part, *lam_m, half, m, **_consts(), BLOCK=BLOCK)
    return _from_mont(part.sum(0).cpu() % PRIME)[0]


def _tree(p: torch.Tensor, q: torch.Tensor) -> list:
    _tick("start", p.device)
    layers = [(p, q)]
    while layers[-1][0].shape[1] > 1:
        layers.append(_combine(*layers[-1]))
    _tick("tree", p.device)
    return layers[::-1]


def prove(p: torch.Tensor, q: torch.Tensor, ch, label: str, device="cuda"):
    """:func:`logup_gkr.prove` on the GPU for canonical leaves ``p, q`` ``[2^n, 8]`` (int64, any device)."""
    return _prove_tree(_tree(_planes_mont(p, device), _planes_mont(q, device)), ch, label)


