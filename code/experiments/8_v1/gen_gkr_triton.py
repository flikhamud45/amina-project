def emul():
    lines = [f"@triton.jit", f"def _emul({args('a')}, {args('b')}, P, MU, B11):",
             '    """``a b`` in ``F_{p^8}`` (Montgomery planes): ``c_k = sum_{i+j=k} a_i b_j + 11 sum_{i+j=k+8} a_i b_j``."""']
    for k in range(D):
        low = [(i, k - i) for i in range(D) if 0 <= k - i < D]
        high = [(i, k + D - i) for i in range(D) if 0 <= k + D - i < D]
        expr = None
        for i, j in low:
            term = f"_mm(a{i}, b{j}, P, MU)"
            expr = term if expr is None else f"_add({expr}, {term}, P)"
        lines.append(f"    c{k} = {expr}")
        if high:
            h = None
            for i, j in high:
                term = f"_mm(a{i}, b{j}, P, MU)"
                h = term if h is None else f"_add({h}, {term}, P)"
            lines.append(f"    c{k} = _add(c{k}, _mm({h}, B11, P, MU), P)")
    lines.append(f"    return {args('c')}")
    return "\n".join(lines)


def load(name, ptr, idx, stride, mask):
    return "\n".join(f"    {name}{k} = tl.load({ptr} + {k} * {stride} + {idx}, mask={mask}, other=0).to(tl.uint32, bitcast=True)"
                     for k in range(D))


def store(name, ptr, idx, stride, mask):
    return "\n".join(f"    tl.store({ptr} + {k} * {stride} + {idx}, {name}{k}.to(tl.int32, bitcast=True), mask={mask})"
                     for k in range(D))


def ext2(fn, out, a, b):
    return "\n".join(f"    {out}{k} = {fn}({a}{k}, {b}{k}, P)" for k in range(D))


def emul_call(out, a, b):
    return f"    {args(out)} = _emul({args(a)}, {args(b)}, P, MU, B11)"


