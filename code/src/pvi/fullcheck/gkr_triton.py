R_MOD = (1 << 32) % PRIME
R2 = (1 << 64) % PRIME
R_INV = pow(1 << 32, -1, PRIME)
MU = pow(PRIME, -1, 1 << 32)
B11 = 11 * R_MOD % PRIME
BLOCK = 256


def available(device) -> bool:
    return triton is not None and torch.device(device).type == "cuda"


def _to_mont(v: torch.Tensor) -> list[int]:
    """Canonical ``[8]`` -> 8 Montgomery ints."""
    return [int(c) * R_MOD % PRIME for c in v.tolist()]


def _from_mont(planes: torch.Tensor) -> torch.Tensor:
    """Montgomery values (int64 tensor, any shape, in ``[0, p)``) -> canonical int64."""
    return (planes.to(torch.int64) % PRIME) * R_INV % PRIME


def _consts():
    return dict(P_=PRIME, MU_=MU, B11_=B11)


if triton is not None:
    @triton.jit
    def _mm(a, b, P, MU):
        lo = a * b
        hi = tl.umulhi(a, b)
        q = lo * MU
        u = tl.umulhi(q, P)
        t = hi - u
        return tl.where(hi < u, t + P, t)

    @triton.jit
    def _add(a, b, P):
        s = a + b
        return tl.where(s >= P, s - P, s)

    @triton.jit
    def _sub(a, b, P):
        d = a - b
        return tl.where(a < b, d + P, d)


    @triton.jit
    def _emul(a0, a1, a2, a3, a4, a5, a6, a7, b0, b1, b2, b3, b4, b5, b6, b7, P, MU, B11):
        """``a b`` in ``F_{p^8}`` (Montgomery planes): ``c_k = sum_{i+j=k} a_i b_j + 11 sum_{i+j=k+8} a_i b_j``."""
        c0 = _mm(a0, b0, P, MU)
        c0 = _add(c0, _mm(_add(_add(_add(_add(_add(_add(_mm(a1, b7, P, MU), _mm(a2, b6, P, MU), P), _mm(a3, b5, P, MU), P), _mm(a4, b4, P, MU), P), _mm(a5, b3, P, MU), P), _mm(a6, b2, P, MU), P), _mm(a7, b1, P, MU), P), B11, P, MU), P)
        c1 = _add(_mm(a0, b1, P, MU), _mm(a1, b0, P, MU), P)
        c1 = _add(c1, _mm(_add(_add(_add(_add(_add(_mm(a2, b7, P, MU), _mm(a3, b6, P, MU), P), _mm(a4, b5, P, MU), P), _mm(a5, b4, P, MU), P), _mm(a6, b3, P, MU), P), _mm(a7, b2, P, MU), P), B11, P, MU), P)
        c2 = _add(_add(_mm(a0, b2, P, MU), _mm(a1, b1, P, MU), P), _mm(a2, b0, P, MU), P)
        c2 = _add(c2, _mm(_add(_add(_add(_add(_mm(a3, b7, P, MU), _mm(a4, b6, P, MU), P), _mm(a5, b5, P, MU), P), _mm(a6, b4, P, MU), P), _mm(a7, b3, P, MU), P), B11, P, MU), P)
        c3 = _add(_add(_add(_mm(a0, b3, P, MU), _mm(a1, b2, P, MU), P), _mm(a2, b1, P, MU), P), _mm(a3, b0, P, MU), P)
        c3 = _add(c3, _mm(_add(_add(_add(_mm(a4, b7, P, MU), _mm(a5, b6, P, MU), P), _mm(a6, b5, P, MU), P), _mm(a7, b4, P, MU), P), B11, P, MU), P)
        c4 = _add(_add(_add(_add(_mm(a0, b4, P, MU), _mm(a1, b3, P, MU), P), _mm(a2, b2, P, MU), P), _mm(a3, b1, P, MU), P), _mm(a4, b0, P, MU), P)
        c4 = _add(c4, _mm(_add(_add(_mm(a5, b7, P, MU), _mm(a6, b6, P, MU), P), _mm(a7, b5, P, MU), P), B11, P, MU), P)
        c5 = _add(_add(_add(_add(_add(_mm(a0, b5, P, MU), _mm(a1, b4, P, MU), P), _mm(a2, b3, P, MU), P), _mm(a3, b2, P, MU), P), _mm(a4, b1, P, MU), P), _mm(a5, b0, P, MU), P)
        c5 = _add(c5, _mm(_add(_mm(a6, b7, P, MU), _mm(a7, b6, P, MU), P), B11, P, MU), P)
        c6 = _add(_add(_add(_add(_add(_add(_mm(a0, b6, P, MU), _mm(a1, b5, P, MU), P), _mm(a2, b4, P, MU), P), _mm(a3, b3, P, MU), P), _mm(a4, b2, P, MU), P), _mm(a5, b1, P, MU), P), _mm(a6, b0, P, MU), P)
        c6 = _add(c6, _mm(_mm(a7, b7, P, MU), B11, P, MU), P)
        c7 = _add(_add(_add(_add(_add(_add(_add(_mm(a0, b7, P, MU), _mm(a1, b6, P, MU), P), _mm(a2, b5, P, MU), P), _mm(a3, b4, P, MU), P), _mm(a4, b3, P, MU), P), _mm(a5, b2, P, MU), P), _mm(a6, b1, P, MU), P), _mm(a7, b0, P, MU), P)
        return c0, c1, c2, c3, c4, c5, c6, c7

    @triton.jit(do_not_specialize=['al0', 'al1', 'al2', 'al3', 'al4', 'al5', 'al6', 'al7', 'rows', 'T', 'n_col', 'total', 'stride', 'P_', 'MU_', 'R2_', 'ONE_'])
    def _leaf_kernel(d_ptr, w_ptr, p_ptr, q_ptr, al0, al1, al2, al3, al4, al5, al6, al7, rows, T, n_col, total, stride, P_, MU_, R2_, ONE_,
                     BLOCK: tl.constexpr):
        P = P_.to(tl.uint32)
        MU = MU_.to(tl.uint32)
        R2 = R2_.to(tl.uint32)
        ONE = ONE_.to(tl.uint32)
        i = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK)
        inb = i < total
        row = i >> n_col
        col = i & ((1 << n_col) - 1)
        real = (row < rows) & (col < T) & inb
        src = row * T + col
        d = tl.load(d_ptr + src, mask=real, other=0).to(tl.uint32, bitcast=True)
        w = tl.load(w_ptr + src, mask=real, other=0).to(tl.uint32, bitcast=True)
        dm = _mm(d, R2, P, MU)
        wm = _mm(w, R2, P, MU)
        zero = d * 0
        q0 = tl.where(real, _sub(al0.to(tl.uint32), dm, P), ONE + zero)
        q1 = tl.where(real, _sub(al1.to(tl.uint32), wm, P), zero)
        q2 = tl.where(real, al2.to(tl.uint32) + zero, zero)
        q3 = tl.where(real, al3.to(tl.uint32) + zero, zero)
        q4 = tl.where(real, al4.to(tl.uint32) + zero, zero)
        q5 = tl.where(real, al5.to(tl.uint32) + zero, zero)
        q6 = tl.where(real, al6.to(tl.uint32) + zero, zero)
        q7 = tl.where(real, al7.to(tl.uint32) + zero, zero)
        p0 = tl.where(real, ONE + zero, zero)
        tl.store(p_ptr + 0 * stride + i, p0.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 1 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 2 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 3 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 4 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 5 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 6 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(p_ptr + 7 * stride + i, zero.to(tl.int32, bitcast=True), mask=inb)
        tl.store(q_ptr + 0 * stride + i, q0.to(tl.int32, bitcast=True), mask=inb)
        tl.store(q_ptr + 1 * stride + i, q1.to(tl.int32, bitcast=True), mask=inb)
        tl.store(q_ptr + 2 * stride + i, q2.to(tl.int32, bitcast=True), mask=inb)
        tl.store(q_ptr + 3 * stride + i, q3.to(tl.int32, bitcast=True), mask=inb)
