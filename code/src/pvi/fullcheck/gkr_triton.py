"""The fractional-sum GKR prover of V1 on the GPU (Triton): ``V1_SPEC.md`` Sec. 5.4.

Generated by ``gen_gkr_triton.py`` (the product in ``F_{p^8}`` is unrolled); same transcript as
:func:`logup_gkr.prove`, byte for byte (``tests/test_gkr_triton.py``, on a CUDA host).

**Arithmetic.** BabyBear in Montgomery form on uint32 (``R = 2^32``): ``mm(a, b) = a b R^-1 mod p`` by
``lo = a b``, ``hi = umulhi(a, b)``, ``q = lo p^-1 mod 2^32``, ``t = hi - umulhi(q, p)`` (``+ p`` if negative); sums by
an add and a conditional subtraction.  An element of ``F = F_p[x]/(x^8 - 11)`` is 8 planes; arrays are
structure-of-arrays ``[8, n]`` int32 tensors (the bits of the uint32 values).  The verifier-facing values (the top,
the round polynomials, the child values) are converted to canonical form on the host.

**Algorithm** (the eager prover's transcript): the leaves of an instance are built on the device from the residues
and widths (``prove_leaves``) or uploaded (``prove``); the tree is combined layer by layer; for each layer ``k`` the
child arrays are split into their even and odd halves.  Round ``j`` writes ``g_j(t) = s_j eq(rho_j, t) h_j(t)``,
``s_j = prod_{i<j} eq(rho_i, r_i)``, ``h_j(t) = sum_y eq(rho_{>j}, y) F(t, y)`` of degree 2 with
``F = PL QR + QL (PR + lambda QR)``: one kernel (``_round2_kernel``) sums ``h_j(0), h_j(1), h_j(2)`` per block in 64
bits over the suffix eq table (built once per layer, never folded), the host extrapolates ``h_j(3)`` and sends the
eager prover's ``g_j(0), g_j(2), g_j(3)`` (a few products per round on Python ints); then one fold of the four child
arrays at the round's challenge (``_fold4_kernel``).  Per pair and round: 16 products in ``F`` instead of the direct
evaluation's 20, and no claim, inverse or interpolation on the host.
"""

